// Generates public/sitemap.xml from the actual data modules so every product,
// series, service and blog post URL is discoverable. Run by `bun run build`
// (pre-write) and standalone via `bun run generate-sitemap`.
// Uses scripts/stub-assets.ts so image imports resolve to "" — identical to
// scripts/mcp-snapshot.ts.
import { products, seriesList } from "../src/data/products";
import { services } from "../src/data/services";
import { blogPosts } from "../src/data/blogPosts";
import { site } from "../src/config/site";

const today = new Date().toISOString().slice(0, 10);

// Static top-level routes (transactional / admin / 404 excluded on purpose).
const STATIC_ROUTES = [
  "/",
  "/shop",
  "/series",
  "/room-packages",
  "/services",
  "/materials",
  "/projects",
  "/custom-design",
  "/blog",
  "/about",
  "/b2b",
  "/contact",
  "/showrooms",
  "/virtual-showroom",
  "/warranty",
  "/quotation",
];

interface Entry {
  path: string;
  changefreq: string;
  priority: string;
}

const entries: Entry[] = [
  ...STATIC_ROUTES.map((path) => ({
    path,
    changefreq: path === "/" ? "weekly" : "monthly",
    priority: path === "/" ? "1.0" : path === "/shop" ? "0.9" : "0.6",
  })),
  // Dynamic catalogue & content — walked from the single source of truth.
  ...products.map((p) => ({ path: `/shop/${p.id}`, changefreq: "weekly", priority: "0.8" })),
  ...seriesList.map((s) => ({ path: `/series/${s.id}`, changefreq: "monthly", priority: "0.7" })),
  ...services.map((s) => ({ path: `/services/${s.slug}`, changefreq: "monthly", priority: "0.6" })),
  ...blogPosts.map((b) => ({ path: `/blog/${b.id}`, changefreq: "yearly", priority: "0.5" })),
];

// De-dupe on path (data modules may repeat ids across groups)
const seen = new Set<string>();
const unique = entries.filter((e) => (seen.has(e.path) ? false : (seen.add(e.path), true)));

const xml = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
  `  <!-- Generated by scripts/generate-sitemap.ts on ${today} — ${unique.length} URLs. Do not edit by hand. -->`,
  ...unique.map(
    (e) =>
      `  <url><loc>${site.url}${e.path}</loc><lastmod>${today}</lastmod><changefreq>${e.changefreq}</changefreq><priority>${e.priority}</priority></url>`,
  ),
  "</urlset>",
  "",
].join("\n");

await Bun.write("public/sitemap.xml", xml);
console.log(`sitemap.xml: ${unique.length} URLs (${products.length} products, ${seriesList.length} series, ${services.length} services, ${blogPosts.length} posts)`);
