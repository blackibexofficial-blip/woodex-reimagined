<?php

declare(strict_types=1);

namespace App\Domain\Website\Content;

use App\Domain\Website\Models\Redirect;

/**
 * Turns the redirect table into the two artefacts that make a 301 happen before a page is served.
 *
 * A stored redirect is a promise the web server has to keep, and nothing in `public/.htaccess` was keeping it:
 * the storefront's fallback (`RewriteRule ^ index.html`) answers any address that is not a file **before** Laravel
 * runs, so every one of the 137 legacy URLs returned the shop with a **200**. The row existed, the screen listed
 * it, and no visitor or crawler ever saw a redirect.
 *
 * So publishing writes the map where the request is actually decided:
 *
 *   * `public/.htaccess` — a generated block at the top of the file, because rules run in order and this one has
 *     to run before the storefront fallback. Real 301s, no PHP in the path, ~137 lines.
 *   * `public/redirects.json` — the same map for the sandbox preview server, which mirrors `.htaccess` in
 *     JavaScript and has no Apache to read the block. One source, two renderings, written together so they
 *     cannot disagree.
 *
 * Only addresses made of `[a-z0-9/-]` become rules. Anything else — a query string, a capital, a space — is
 * skipped and reported rather than escaped into a regex nobody can read: a wrong `RewriteRule` is worse than a
 * missing one, because it fires on somebody else's URL.
 */
final class RedirectPublisher
{
    public const string START = '# BEGIN WOODEX REDIRECTS — generated by `website:publish`, edits are lost';

    public const string END = '# END WOODEX REDIRECTS';

    /** The characters a path may contain to become a rule, matching what `LegacyRedirects` and the admin emit. */
    private const string SAFE = '#^/[a-z0-9/\-]*/$#';

    public function __construct(private readonly ?string $webroot = null) {}

    public function root(): string
    {
        return rtrim($this->webroot ?? (function_exists('public_path') ? public_path() : getcwd()), '/');
    }

    /**
     * The RewriteRule lines for a set of rows, and the ones this will not emit.
     *
     * Pure, so the grammar is testable: a rule is `^path/?$` → target, permanent and last, and a row pointing at
     * itself is dropped here as well as in the screen, because a self-redirect in `.htaccess` is an infinite loop
     * the browser hides and a crawler reports as an error.
     *
     * @param  iterable<array{from_path: string, to_path: string, code: int|string}>  $rows
     * @return array{lines: list<string>, skipped: list<string>}
     */
    public static function rules(iterable $rows): array
    {
        $lines = [];
        $skipped = [];
        $seen = [];

        foreach ($rows as $row) {
            $from = LegacyRedirects::path((string) ($row['from_path'] ?? ''));
            $to = (string) ($row['to_path'] ?? '');
            $code = (int) ($row['code'] ?? 301);

            if ($from === '/' || $from === $to || isset($seen[$from]) || preg_match(self::SAFE, $from) !== 1) {
                $skipped[] = $from;

                continue;
            }

            $seen[$from] = true;

            // Per-directory rewrite rules match without the leading slash. The optional trailing slash keeps
            // `/about` and `/about/` on one rule, which matters because the interior site linked to both.
            $pattern = '^'.substr($from, 1).'?$';
            $lines[] = sprintf('    RewriteRule %s %s [R=%d,L]', $pattern, self::quote($to), $code === 302 ? 302 : 301);
        }

        return ['lines' => $lines, 'skipped' => $skipped];
    }

    /**
     * Write the block and the manifest. Returns how many rules were written and which rows were left out.
     *
     * @return array{rules: int, skipped: list<string>, file: string}
     */
    public function write(iterable $rows): array
    {
        $rows = is_array($rows) ? $rows : iterator_to_array($rows, false);
        $plan = self::rules($rows);

        $block = [self::START];

        if ($plan['lines'] === []) {
            $block[] = '    # No redirects are configured.';
        } else {
            $block[] = '    RewriteEngine On';
            $block[] = '    # The archived interior site\'s URLs, and anything else the owner has redirected.';
            $block = [...$block, ...$plan['lines']];
        }

        $block[] = self::END;

        $htaccess = $this->root().'/.htaccess';

        if (is_file($htaccess)) {
            $existing = (string) file_get_contents($htaccess);
            $stripped = preg_replace('/'.preg_quote(self::START, '/').'.*?'.preg_quote(self::END, '/').'\n?/s', '', $existing) ?? $existing;
            // At the top, because the storefront's fallback is at the bottom and would answer first.
            file_put_contents($htaccess, implode("\n", $block)."\n\n".ltrim($stripped));
        }

        $manifest = [];

        foreach ($rows as $row) {
            $from = LegacyRedirects::path((string) ($row['from_path'] ?? ''));
            $manifest[$from] = ['to' => (string) ($row['to_path'] ?? ''), 'code' => (int) ($row['code'] ?? 301)];
        }

        file_put_contents(
            $this->root().'/redirects.json',
            json_encode($manifest, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES)."\n",
        );

        return ['rules' => count($plan['lines']), 'skipped' => $plan['skipped'], 'file' => $htaccess];
    }

    /** @return list<array{from_path: string, to_path: string, code: int}> */
    public static function rows(): array
    {
        return Redirect::query()
            ->orderBy('from_path')
            ->get(['from_path', 'to_path', 'code'])
            ->map(fn (Redirect $row): array => [
                'from_path' => (string) $row->from_path,
                'to_path' => (string) $row->to_path,
                'code' => (int) $row->code,
            ])
            ->all();
    }

    /** A target with spaces quoted, because an unquoted space ends the rule and silently changes its meaning. */
    private static function quote(string $to): string
    {
        return str_contains($to, ' ') ? '"'.$to.'"' : $to;
    }
}
